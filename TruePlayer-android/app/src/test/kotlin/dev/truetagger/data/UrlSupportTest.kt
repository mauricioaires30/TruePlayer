package dev.truetagger.data

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class UrlSupportTest {
    @Test fun recognizesYoutubeAndSoundcloudHosts() {
        listOf(
            "https://www.youtube.com/watch?v=abc", "https://youtu.be/abc", "https://music.youtube.com/watch?v=abc",
            "https://m.youtube.com/watch?v=abc",
        ).forEach { assertEquals(it, UrlSupport.Source.YOUTUBE, UrlSupport.source(it)) }
        listOf("https://soundcloud.com/artista/faixa", "https://m.soundcloud.com/a/b", "https://on.soundcloud.com/xyz")
            .forEach { assertEquals(it, UrlSupport.Source.SOUNDCLOUD, UrlSupport.source(it)) }
    }

    @Test fun otherSitesAndGarbageAreNotSupported() {
        assertNull(UrlSupport.source("https://example.com/video"))
        assertNull(UrlSupport.source("https://notyoutube.com/watch?v=1"))
        assertFalse(UrlSupport.isSupported("isso nao e link"))
    }

    @Test fun youtubePlaylistPageIsAPlaylist() {
        assertTrue(UrlSupport.isPlaylist("https://www.youtube.com/playlist?list=PLabc123"))
        assertTrue(UrlSupport.isPlaylist("https://music.youtube.com/playlist?list=OLAK5uy_xyz"))
    }

    @Test fun videoInsideAPlaylistCountsAsASingleSong() {
        assertFalse(UrlSupport.isPlaylist("https://www.youtube.com/watch?v=abc&list=PLabc123"))
    }

    @Test fun autoGeneratedMixesAreNotPlaylists() {
        assertFalse(UrlSupport.isPlaylist("https://www.youtube.com/playlist?list=RDabc"))
    }

    @Test fun soundcloudSetIsAPlaylistButTheSetsIndexIsNot() {
        assertTrue(UrlSupport.isPlaylist("https://soundcloud.com/artista/sets/meu-album"))
        assertFalse(UrlSupport.isPlaylist("https://soundcloud.com/artista/sets"))
        assertFalse(UrlSupport.isPlaylist("https://soundcloud.com/artista/faixa"))
    }

    @Test fun shortSoundcloudLinksAreListedFirst() {
        assertTrue(UrlSupport.needsListing("https://on.soundcloud.com/abc"))
        assertTrue(UrlSupport.needsListing("https://soundcloud.com/a/sets/b"))
        assertFalse(UrlSupport.needsListing("https://youtu.be/abc"))
    }

    @Test fun spotifyLinksAreNotDownloadableButAreRecognizedForTheWarning() {
        listOf(
            "https://open.spotify.com/track/0VjIjW4GlUZAMYd2vXMi3b", "https://open.spotify.com/playlist/37i9dQZF1DX4UtSsGT1Sbe?si=x",
            "https://spotify.link/abc", "https://open.spotify.com/intl-pt/album/4yP0hdKOZPNshxUOjY0cZj",
        ).forEach {
            assertFalse(it, UrlSupport.isSupported(it))
            assertTrue(it, UrlSupport.isSpotify(it))
            assertNull(it, UrlSupport.source(it))
            assertFalse(it, UrlSupport.needsListing(it))
        }
        assertFalse(UrlSupport.isSpotify("https://www.youtube.com/watch?v=abc"))
        assertFalse(UrlSupport.isSpotify("não é link"))
    }
}
